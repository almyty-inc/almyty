import {
  CURATED_TOOL_ROUTES,
  EXCLUDED_ROUTES,
  HELD_ROUTES,
  OPERATIONS,
  effectOf,
} from '../modules/mcp/management/management-operations';
import { ControllerRoute } from './controller-routes';

/**
 * docs/design/almyty-mcp-coverage.md, built from the controllers' routes
 * and the management MCP's coverage lists. `npm run mcp:coverage` writes
 * it; management-coverage.guard.spec.ts fails when the file and this
 * output differ, so the matrix cannot go stale.
 */

export type CoverageStatus = 'tool' | 'operation' | 'excluded' | 'held' | 'unmapped';

export interface CoverageRow {
  route: ControllerRoute;
  status: CoverageStatus;
  /** The tool or operation, or the reason / open question. */
  covers: string;
}

/** The resource a route belongs to: its module directory (`agents`, `gateways`, `ee/rbac`). */
export function resourceOf(route: ControllerRoute): string {
  const m = route.file.match(/^(src|ee)\/modules\/([^/]+)/);
  if (!m) return 'other';
  return m[1] === 'ee' ? `ee/${m[2]}` : m[2];
}

export function coverageRows(routes: ControllerRoute[]): CoverageRow[] {
  const toolsByRoute = new Map<string, string[]>();
  for (const [tool, refs] of Object.entries(CURATED_TOOL_ROUTES)) {
    for (const ref of refs) toolsByRoute.set(ref, [...(toolsByRoute.get(ref) ?? []), tool]);
  }
  const opsByRoute = new Map(OPERATIONS.map((op) => [op.route, op]));
  return routes.map((route) => {
    const tools = toolsByRoute.get(route.ref);
    if (tools) return { route, status: 'tool', covers: tools.map((t) => `\`${t}\``).join(', ') };
    const op = opsByRoute.get(route.ref);
    if (op) return { route, status: 'operation', covers: `\`${op.name}\` (${effectOf(op, route.method)})` };
    if (EXCLUDED_ROUTES[route.ref]) return { route, status: 'excluded', covers: '' };
    if (HELD_ROUTES[route.ref]) return { route, status: 'held', covers: HELD_ROUTES[route.ref] };
    return { route, status: 'unmapped', covers: '' };
  });
}

export interface CoverageCounts {
  routes: number;
  excluded: number;
  inScope: number;
  tool: number;
  operation: number;
  held: number;
  unmapped: number;
}

export function coverageCounts(rows: CoverageRow[]): CoverageCounts {
  const n = (s: CoverageStatus) => rows.filter((r) => r.status === s).length;
  const excluded = n('excluded');
  return {
    routes: rows.length,
    excluded,
    inScope: rows.length - excluded,
    tool: n('tool'),
    operation: n('operation'),
    held: n('held'),
    unmapped: n('unmapped'),
  };
}

const pct = (part: number, whole: number) => `${((100 * part) / Math.max(whole, 1)).toFixed(1)}%`;
const cell = (text: string) => text.replace(/\|/g, '\\|');

/** The generated part of the coverage document. */
export function coverageMarkdown(routes: ControllerRoute[]): string {
  const rows = coverageRows(routes);
  const c = coverageCounts(rows);
  const lines: string[] = [];
  lines.push('<!-- generated by `npm run mcp:coverage` (backend); do not edit by hand -->');
  lines.push('');
  lines.push('## Numbers');
  lines.push('');
  lines.push('| | Routes |');
  lines.push('| --- | ---: |');
  lines.push(`| Controller routes (src/modules + ee/modules) | ${c.routes} |`);
  lines.push(`| Excluded (an MCP client must not or cannot use them) | ${c.excluded} |`);
  lines.push(`| In scope | ${c.inScope} |`);
  lines.push(`| Covered by a dedicated tool | ${c.tool} (${pct(c.tool, c.inScope)}) |`);
  lines.push(`| Covered by an operation | ${c.operation} (${pct(c.operation, c.inScope)}) |`);
  lines.push(`| Covered in total | ${c.tool + c.operation} (${pct(c.tool + c.operation, c.inScope)}) |`);
  lines.push(`| Held for a product decision | ${c.held} (${pct(c.held, c.inScope)}) |`);
  lines.push('');

  lines.push('## By resource');
  lines.push('');
  lines.push('| Resource | Routes | Tool | Operation | Held | Excluded |');
  lines.push('| --- | ---: | ---: | ---: | ---: | ---: |');
  const resources = [...new Set(rows.map((r) => resourceOf(r.route)))].sort();
  for (const res of resources) {
    const rs = rows.filter((r) => resourceOf(r.route) === res);
    const n = (s: CoverageStatus) => rs.filter((r) => r.status === s).length;
    lines.push(`| ${res} | ${rs.length} | ${n('tool')} | ${n('operation')} | ${n('held')} | ${n('excluded')} |`);
  }
  lines.push('');

  lines.push('## Matrix');
  lines.push('');
  lines.push('Status: **tool** = a dedicated MCP tool; **operation** = `search_operations` / `get_operation` / `call_<effect>_operation`; **held** = waits for a product decision; **excluded** = see the next section.');
  lines.push('');
  lines.push('| Resource | Operation (route) | MCP tool | Status |');
  lines.push('| --- | --- | --- | --- |');
  for (const r of rows) {
    const covers = r.status === 'held' ? '' : r.covers;
    lines.push(`| ${resourceOf(r.route)} | \`${r.route.method} ${r.route.path}\` (${r.route.ref}) | ${cell(covers)} | ${r.status} |`);
  }
  lines.push('');

  lines.push('## Exclusions');
  lines.push('');
  const byReason = new Map<string, string[]>();
  for (const [ref, reason] of Object.entries(EXCLUDED_ROUTES)) byReason.set(reason, [...(byReason.get(reason) ?? []), ref]);
  for (const [reason, refs] of byReason) {
    lines.push(`- ${reason}`);
    lines.push(`  ${refs.map((r) => `\`${r}\``).join(', ')}`);
  }
  lines.push('');

  lines.push('## Held for a product decision');
  lines.push('');
  lines.push('| Route | Question |');
  lines.push('| --- | --- |');
  for (const [ref, question] of Object.entries(HELD_ROUTES)) {
    const route = routes.find((r) => r.ref === ref);
    lines.push(`| \`${route ? `${route.method} ${route.path}` : ref}\` (${ref}) | ${cell(question)} |`);
  }
  lines.push('');
  return lines.join('\n');
}

export const GENERATED_START = '<!-- coverage:start -->';
export const GENERATED_END = '<!-- coverage:end -->';

/** The document with its generated section replaced by `generated`. */
export function withGeneratedSection(doc: string, generated: string): string {
  const start = doc.indexOf(GENERATED_START);
  const end = doc.indexOf(GENERATED_END);
  if (start < 0 || end < start) throw new Error('coverage markers missing from the document');
  return `${doc.slice(0, start + GENERATED_START.length)}\n${generated}\n${doc.slice(end)}`;
}
